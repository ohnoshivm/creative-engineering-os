import './styles.css';
import {canUseWebGL2,prefersReducedMotion,stillMode} from './core/env';
import {createLoop} from './core/loop';
import {createPointer} from './core/pointer';
import {initMotion,type ScrollStore} from './motion/sections';
const scroll:ScrollStore={heroProgress:0};const destroyMotion=initMotion(scroll);
const host=document.querySelector<HTMLElement>('[data-stage]')!;
const range=document.querySelector<HTMLInputElement>('#tension')!;
const output=document.querySelector<HTMLOutputElement>('#tension-value')!;
const button=document.querySelector<HTMLButtonElement>('#pause')!;
const instructions=document.querySelector<HTMLElement>('#instructions')!;
const coarse=matchMedia('(pointer: coarse)');
const updateInstructions=()=>{instructions.innerText=prefersReducedMotion()?'Still view.\nAdjust Surface tension below.':coarse.matches?'Adjust Surface tension below.\nScroll to shift the phase.':'Move across the surface.\nScroll to shift its phase.';};
coarse.addEventListener('change',updateInstructions);updateInstructions();
let paused=false,renderStill=()=>{},sync=()=>{};
const onRange=()=>{output.value=`${range.value}%`;renderStill();};
const updateControl=()=>{button.disabled=prefersReducedMotion();button.textContent=prefersReducedMotion()?'Motion reduced':paused?'Resume motion':'Pause motion';button.title=prefersReducedMotion()?'Motion follows your system preference':'';button.setAttribute('aria-pressed',String(paused));};
const onPause=()=>{paused=!paused;updateControl();sync();renderStill();};
range.addEventListener('input',onRange);button.addEventListener('click',onPause);
async function mount(){
 const{createStage}=await import('./gl/stage');const stage=createStage(host);const pointer=createPointer(host);const loop=createLoop();
 const media=matchMedia('(prefers-reduced-motion: reduce)');let visible=true,elapsed=1.2,lost=false;
 const input=()=>({pointer:pointer.state,fold:scroll.heroProgress,tension:Number(range.value)/100});
 const fixed=()=>media.matches||stillMode();
 renderStill=()=>{if(!lost&&(fixed()||paused))stage.still({...input(),pointer:{x:0,y:0}});};
 sync=()=>{if(visible&&!document.hidden&&!paused&&!fixed()&&!lost)loop.start();else loop.stop();};
 loop.add((_time,dt)=>{elapsed+=dt;stage.frame(elapsed,dt,input());});
 const io=new IntersectionObserver(([entry])=>{visible=entry.isIntersecting;sync();});io.observe(host);
 const onPreference=()=>{updateInstructions();updateControl();sync();renderStill();};media.addEventListener('change',onPreference);document.addEventListener('visibilitychange',sync);
 const onLost=(e:Event)=>{e.preventDefault();lost=true;loop.stop();host.classList.remove('is-live');document.documentElement.dataset.stage='poster';};
 const onRestored=()=>{lost=false;host.classList.add('is-live');document.documentElement.dataset.stage='live';sync();renderStill();};
 stage.canvas.addEventListener('webglcontextlost',onLost);stage.canvas.addEventListener('webglcontextrestored',onRestored);
 stage.still({...input(),pointer:{x:0,y:0}});host.classList.add('is-live');document.documentElement.dataset.stage='live';sync();
 return()=>{io.disconnect();loop.destroy();pointer.destroy();media.removeEventListener('change',onPreference);document.removeEventListener('visibilitychange',sync);stage.canvas.removeEventListener('webglcontextlost',onLost);stage.canvas.removeEventListener('webglcontextrestored',onRestored);stage.destroy();};
}
let destroyStage:(()=>void)|undefined;
if(canUseWebGL2())mount().then(d=>{destroyStage=d;}).catch(()=>{document.documentElement.dataset.stage='poster';});else document.documentElement.dataset.stage='poster';
updateControl();
if(import.meta.hot)import.meta.hot.dispose(()=>{destroyStage?.();destroyMotion();range.removeEventListener('input',onRange);button.removeEventListener('click',onPause);coarse.removeEventListener('change',updateInstructions);});
